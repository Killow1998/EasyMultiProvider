use crate::http::auth::session_header_value;
use crate::server::http::body::BodyError;
use std::time::Duration;

pub(crate) const MAX_HEADER_BYTES: usize = 8 * 1024;

pub(crate) const REQUEST_READ_TIMEOUT: Duration = Duration::from_secs(5);
pub(crate) const REQUEST_HEAD_DEADLINE: Duration = Duration::from_secs(30);
const REQUEST_BODY_DEADLINE: Duration = Duration::from_secs(120);
const REQUEST_BODY_GRACE_BYTES_PER_SECOND: usize = 1024 * 1024;
pub(crate) const REQUEST_VERSION: &str = "HTTP/1.1";

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum RequestMethod {
    Get,
    Head,
    Post,
    Delete,
}

impl RequestMethod {
    pub(crate) const fn as_str(self) -> &'static str {
        match self {
            Self::Get => "GET",
            Self::Head => "HEAD",
            Self::Post => "POST",
            Self::Delete => "DELETE",
        }
    }
}

#[derive(Clone, Copy)]
pub(crate) struct Request<'a> {
    pub(crate) method: RequestMethod,
    pub(crate) target: &'a str,
    pub(crate) headers: &'a str,
    /// Generated by the connection owner; never read from client headers.
    pub(crate) observation_id: Option<&'a str>,
    pub(crate) source: Option<&'a RequestSource>,
}

#[derive(Clone)]
pub(crate) struct RequestSource {
    pub(crate) caller: Option<crate::services::gateway_clients::Caller>,
    pub(crate) peer: Option<std::net::IpAddr>,
    pub(crate) delegation: Option<crate::services::modules::aero::CallerDelegation>,
    pub(crate) aero_lease: Option<crate::services::modules::aero::CallLease>,
}

impl<'a> Request<'a> {
    pub(crate) fn incoming(&self) -> std::collections::BTreeMap<String, String> {
        let mut headers: std::collections::BTreeMap<_, _> = self
            .headers
            .lines()
            .skip(1)
            .filter_map(|line| line.split_once(':'))
            .map(|(name, value)| (name.trim().to_ascii_lowercase(), value.trim().to_owned()))
            .filter(|(name, _)| !reserved_source_header(name))
            .collect();
        if let Some(source) = self.source {
            if let Some(delegation) = &source.delegation {
                headers.remove("authorization");
                if let Some(authorization) = &delegation.authorization {
                    headers.insert("authorization".into(), authorization.clone());
                }
            }
            if let Some(caller) = &source.caller {
                headers.insert("x-emp-caller-id".into(), caller.id.clone());
                headers.insert("x-emp-caller-name".into(), caller.name.clone());
            }
            if let Some(peer) = source.peer {
                headers.insert("x-emp-peer-ip".into(), peer.to_string());
            }
        }
        headers
    }
    pub(crate) fn header(&self, name: &str) -> Option<&'a str> {
        self.headers.lines().skip(1).find_map(|line| {
            let (header_name, value) = line.split_once(':')?;
            let header_name = header_name.trim();
            (!reserved_source_header(header_name) && header_name.eq_ignore_ascii_case(name))
                .then(|| value.trim())
        })
    }

    pub(crate) fn header_count(&self, name: &str) -> usize {
        self.headers
            .lines()
            .skip(1)
            .filter_map(|line| line.split_once(':'))
            .filter(|(header_name, _)| header_name.trim().eq_ignore_ascii_case(name))
            .count()
    }

    pub(crate) fn raw_path(&self) -> &'a str {
        self.target
            .split_once('?')
            .map_or(self.target, |(path, _)| path)
    }

    pub(crate) fn is_model_http(&self) -> bool {
        self.method == RequestMethod::Post
            && matches!(self.raw_path(), "/v1/responses" | "/v1/responses/compact")
    }

    pub(crate) fn validate_body_framing(&self) -> Result<(), BodyError> {
        if self.header_count("Content-Length") > 1 || self.header_count("Transfer-Encoding") > 0 {
            return Err(BodyError::Invalid(
                "duplicate Content-Length or unsupported Transfer-Encoding".to_owned(),
            ));
        }
        Ok(())
    }

    /// The management session presented in the `X-EMP-Session` header.
    /// Cookies are never consulted: browsers share them across local ports.
    pub(crate) fn session_token(&self) -> Option<String> {
        session_header_value(*self)
    }
}

pub(crate) fn reserved_source_header(name: &str) -> bool {
    name.eq_ignore_ascii_case("x-emp-peer-ip")
        || name
            .get(.."x-emp-caller-".len())
            .is_some_and(|prefix| prefix.eq_ignore_ascii_case("x-emp-caller-"))
}

pub(crate) struct RequestHead {
    pub(crate) head: String,
    pub(crate) body_prefix: Vec<u8>,
}

pub(crate) fn request_body_timeout(length: usize) -> Duration {
    let grace = (length / REQUEST_BODY_GRACE_BYTES_PER_SECOND) as u64;
    REQUEST_BODY_DEADLINE + Duration::from_secs(grace)
}

pub(crate) fn request_head_end(request: &[u8], previous_len: usize) -> Result<Option<usize>, ()> {
    let search_start = previous_len.saturating_sub(3);
    match request[search_start..]
        .windows(4)
        .position(|window| window == b"\r\n\r\n")
    {
        Some(offset) if search_start + offset <= MAX_HEADER_BYTES => {
            Ok(Some(search_start + offset + 4))
        }
        _ if request.len() <= MAX_HEADER_BYTES + 3 => Ok(None),
        _ => Err(()),
    }
}

fn request_line(request: &str) -> Option<(RequestMethod, &str)> {
    let request_line = request.lines().next()?;
    let mut parts = request_line.split_whitespace();
    let method = match parts.next()? {
        "GET" => RequestMethod::Get,
        "HEAD" => RequestMethod::Head,
        "POST" => RequestMethod::Post,
        "DELETE" => RequestMethod::Delete,
        _ => return None,
    };
    let target = parts.next()?;
    (parts.next()? == REQUEST_VERSION && parts.next().is_none()).then_some((method, target))
}

pub(crate) fn parse_request(request: &str) -> Option<Request<'_>> {
    let headers_end = request.find("\r\n\r\n")?;
    let (method, target) = request_line(request)?;
    Some(Request {
        method,
        target,
        headers: &request[..headers_end],
        observation_id: None,
        source: None,
    })
}

pub(crate) fn percent_decode(raw: &str, plus_to_space: bool) -> String {
    let bytes = raw.as_bytes();
    let mut decoded = Vec::with_capacity(bytes.len());
    let mut index = 0;
    while index < bytes.len() {
        match bytes[index] {
            b'%' if index + 2 < bytes.len() => {
                let high = (bytes[index + 1] as char).to_digit(16);
                let low = (bytes[index + 2] as char).to_digit(16);
                if let (Some(high), Some(low)) = (high, low) {
                    decoded.push((high * 16 + low) as u8);
                    index += 3;
                } else {
                    decoded.push(b'%');
                    index += 1;
                }
            }
            b'+' if plus_to_space => {
                decoded.push(b' ');
                index += 1;
            }
            byte => {
                decoded.push(byte);
                index += 1;
            }
        }
    }
    String::from_utf8_lossy(&decoded).into_owned()
}

pub(crate) fn query_values(target: &str, name: &str) -> Vec<String> {
    let Some((_, query)) = target.split_once('?') else {
        return Vec::new();
    };
    query
        .split('&')
        .filter_map(|pair| pair.split_once('='))
        .filter(|(key, _)| percent_decode(key, true) == name)
        .map(|(_, value)| percent_decode(value, true))
        .collect()
}

#[cfg(test)]
mod tests {
    use std::io::Write as _;
    use std::net::{Ipv4Addr, TcpListener, TcpStream};
    use std::thread;
    use std::time::{Duration, Instant};

    #[test]
    fn request_head_has_an_overall_deadline() {
        let listener = TcpListener::bind((Ipv4Addr::LOCALHOST, 0)).expect("bind");
        let address = listener.local_addr().expect("address");
        let writer = thread::spawn(move || {
            let mut client = TcpStream::connect(address).expect("connect");
            client
                .write_all(b"GET / HTTP/1.1\r\n")
                .expect("request line");
            // Trickle one byte at a time, never finishing the head and never
            // idling long enough for the per-read timeout.
            for _ in 0..40 {
                #[expect(
                    clippy::disallowed_methods,
                    reason = "按固定间隔逐字节发送，验证持续有数据时请求头仍受总时限约束"
                )]
                thread::sleep(Duration::from_millis(50));
                if client.write_all(b"X").is_err() {
                    break;
                }
            }
        });
        let (mut stream, _) = listener.accept().expect("accept");
        let started = Instant::now();
        let head = crate::server::transport::read_request_head_before(
            &mut stream,
            started + Duration::from_millis(400),
        );
        assert!(head.is_none());
        let elapsed = started.elapsed();
        assert!(elapsed >= Duration::from_millis(400), "{elapsed:?}");
        assert!(elapsed < Duration::from_millis(1500), "{elapsed:?}");
        drop(stream);
        writer.join().expect("writer");
    }
}
